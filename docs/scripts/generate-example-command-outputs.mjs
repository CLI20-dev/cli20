import {mkdir, readdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import process from 'node:process';

const docsDir = process.cwd();
const repoRoot = path.resolve(docsDir, '..');
const examplesDir = path.join(docsDir, 'docs', 'examples');
const generatedDir = path.join(docsDir, 'src', 'generated');
const outputFile = path.join(generatedDir, 'exampleCommandOutputs.ts');

const commandPattern = /command:\s*(?:'((?:\\.|[^'])*)'|`([\s\S]*?)`)/g;

function decodeSingleQuoted(text) {
  return text.replace(/\\'/g, "'").replace(/\\\\/g, '\\');
}

function normalizeCommand(match) {
  if (match[1] !== undefined) {
    return decodeSingleQuoted(match[1]);
  }
  return match[2];
}

async function collectCommands() {
  const filenames = await readdir(examplesDir);
  const commands = new Set();

  for (const filename of filenames) {
    if (!filename.endsWith('.mdx')) {
      continue;
    }

    const source = await readFile(path.join(examplesDir, filename), 'utf8');
    for (const match of source.matchAll(commandPattern)) {
      commands.add(normalizeCommand(match));
    }
  }

  return [...commands];
}

function runCommand(command) {
  const result = spawnSync('/bin/zsh', ['-lc', command], {
    cwd: repoRoot,
    encoding: 'utf8',
  });
  const stdout = result.stdout ?? '';
  const stderr = result.stderr ?? '';
  const combined = `${stdout}${stderr}`.trimEnd();
  return combined;
}

function renderModule(entries) {
  const lines = [
    '// This file is auto-generated by docs/scripts/generate-example-command-outputs.mjs.',
    '// Do not edit by hand.',
    '',
    'export const exampleCommandOutputs: Record<string, string> = {',
  ];

  for (const [command, output] of entries) {
    lines.push(`  ${JSON.stringify(command)}: ${JSON.stringify(output)},`);
  }

  lines.push('};', '');
  return lines.join('\n');
}

const commands = await collectCommands();
const entries = commands
  .sort((left, right) => left.localeCompare(right))
  .map(command => [command, runCommand(command)]);

await mkdir(generatedDir, {recursive: true});
await writeFile(outputFile, renderModule(entries), 'utf8');
